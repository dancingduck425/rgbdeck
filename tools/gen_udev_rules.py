#!/usr/bin/env python3
"""Regenerate rgbdeck/data/70-rgbdeck.rules from every driver's USB_IDS. Run after adding a driver."""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from rgbdeck.backend import discover_drivers  # noqa: E402

HEADER = """# RGB Deck: let the logged-in user talk to supported RGB devices directly (generated by tools/gen_udev_rules.py).
# Install:  sudo cp 70-rgbdeck.rules /etc/udev/rules.d/ && sudo udevadm control --reload && sudo udevadm trigger
"""
lines = [HEADER]
seen = set()
for mod in discover_drivers():
    ids = sorted(set(getattr(mod, "USB_IDS", [])))
    if not ids:
        continue
    lines.append(f"# {mod.__name__.rsplit('.', 1)[-1]}")
    for vid, pid in ids:
        if (vid, pid) in seen:
            continue
        seen.add((vid, pid))
        lines.append(
            f'SUBSYSTEMS=="usb|hidraw", ATTRS{{idVendor}}=="{vid:04x}", ATTRS{{idProduct}}=="{pid:04x}", TAG+="uaccess"'
        )
lines.append(
    "# keyboard key presses for the typing effects (logind already grants seat devices; kept for completeness)"
)
lines.append('SUBSYSTEM=="input", ATTRS{idVendor}=="046d", TAG+="uaccess"')
out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "rgbdeck", "data", "70-rgbdeck.rules")
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {out}: {len(seen)} USB ids from {sum(1 for _ in discover_drivers())} drivers")
